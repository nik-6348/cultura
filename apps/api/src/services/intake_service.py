"""
Intake service — conversational project setup.
Claude asks targeted questions, extracts ProjectSpec, confirms, then signals ready.
"""

import json
import logging
from typing import Any

import httpx

from src.core.config import get_settings

logger = logging.getLogger("cultura.services.intake")

INTAKE_SYSTEM = """\
You are the Cultura project setup assistant. Help the user create a new market expansion project.

Your job is to:
1. Collect the required info through friendly, natural conversation
2. Ask ONE clear question at a time when info is missing
3. Suggest relevant markets based on brand/category context
4. When brand + markets are set, confirm the setup and ask to launch

Required fields:
- brand_name   — the brand being expanded (MUST have)
- markets      — list of target cities/metro areas (MUST have at least 1)

Optional but helpful:
- brand_category   — e.g. "streetwear", "food & beverage", "tech", "beauty"
- audience         — target customer description, age range, tier
- objective        — expansion goal in one line

Question order (ask in this sequence, skip if already provided):
1. Brand name + what type (if not given)
2. Target markets — suggest 3-4 relevant ones based on brand/category, let user pick/adjust
3. Target audience (optional — if user skips, that's fine)
4. Once brand + markets confirmed → show summary and ask "Ready to launch?"

When user confirms launch (says "yes", "launch", "go", "run it", "looks good", "proceed"):
- Set "ready": true in your response

ALWAYS return valid JSON with this exact shape (no markdown fences):
{
  "reply": "<your conversational message to the user>",
  "spec": {
    "brand_name": "<string or null>",
    "project_name": "<auto-generated name or null>",
    "brand_category": "<string or null>",
    "markets": [{"name": "<city>", "country_code": "<ISO2 or null>"}],
    "audience_description": "<string or null>",
    "objective": "<string or null>"
  } | null,
  "ready": false
}

Rules:
- Keep replies short (2-3 sentences max), warm and professional
- Never ask about things already provided
- When suggesting markets, give emoji flags: "🇯🇵 Tokyo, 🇰🇷 Seoul, 🇸🇬 Singapore"
- Auto-generate project_name as "<BrandName> — <Region> Expansion" once markets are known
- spec is null until brand_name is known; update it as info accumulates
- ready stays false until user explicitly confirms
"""


async def _call_llm(messages: list[dict[str, str]]) -> str | None:
    settings = get_settings()
    if not settings.llm_api_key or not settings.llm_base_url:
        return None
    try:
        async with httpx.AsyncClient(timeout=20.0) as client:
            res = await client.post(
                f"{settings.llm_base_url.rstrip('/')}/chat/completions",
                headers={
                    "Authorization": f"Bearer {settings.llm_api_key}",
                    "Content-Type": "application/json",
                },
                json={
                    "model": settings.llm_model,
                    "messages": messages,
                    "temperature": 0.4,
                    "max_tokens": 600,
                },
            )
            if res.status_code == 200:
                data = res.json()
                choices = data.get("choices", [])
                if choices and choices[0].get("message", {}).get("content"):
                    return str(choices[0]["message"]["content"]).strip()
    except Exception as exc:
        logger.debug("Intake LLM call failed: %s", exc)
    return None


def _fallback_response(messages: list[dict[str, str]]) -> dict[str, Any]:
    """Rule-based fallback when LLM is unavailable."""
    user_msgs = [m["content"] for m in messages if m["role"] == "user"]
    last = user_msgs[-1].lower() if user_msgs else ""

    # Detect confirmation
    confirm_words = {"yes", "launch", "go", "run", "proceed", "looks good", "perfect", "sure", "do it"}
    if any(w in last for w in confirm_words) and len(user_msgs) >= 2:
        return {
            "reply": "Launching the analysis now!",
            "spec": None,
            "ready": True,
        }

    if len(user_msgs) == 1:
        return {
            "reply": "Got it! Which markets are you targeting? I can suggest Tokyo, Seoul, Singapore, Bangkok, or others based on your brand.",
            "spec": None,
            "ready": False,
        }

    return {
        "reply": "Who is the target customer for this expansion? Feel free to describe age range, lifestyle, or just say 'skip' to proceed.",
        "spec": None,
        "ready": False,
    }


async def process_intake_message(
    messages: list[dict[str, str]],
) -> dict[str, Any]:
    """
    Process one intake conversation turn.
    messages: full conversation so far as [{ role, content }]
    Returns: { reply, spec, ready }
    """
    llm_messages = [{"role": "system", "content": INTAKE_SYSTEM}] + messages

    raw = await _call_llm(llm_messages)
    if not raw:
        return _fallback_response(messages)

    # Parse the JSON response
    try:
        # Strip markdown fences if present
        text = raw.strip()
        if text.startswith("```"):
            text = text.split("```")[1]
            if text.startswith("json"):
                text = text[4:]
        result = json.loads(text)
        return {
            "reply": str(result.get("reply", "")),
            "spec": result.get("spec"),
            "ready": bool(result.get("ready", False)),
        }
    except (json.JSONDecodeError, KeyError, TypeError) as exc:
        logger.debug("Failed to parse intake JSON (%s): %s", exc, raw[:200])
        # Extract reply text if JSON parse failed
        return {
            "reply": raw if len(raw) < 400 else raw[:400] + "…",
            "spec": None,
            "ready": False,
        }
